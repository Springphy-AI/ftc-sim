    /**
     * The tag as TOTAL_WIDTH x TOTAL_WIDTH cells, row by row from the top-left, true = white. Same
     * layout as apriltag_to_image(): a white outer ring, a black ring, then the data bits.
     */
    public static boolean[] cells(int id) {
        if (id < 0 || id >= CODES.length) throw new IllegalArgumentException("tag36h11 has no id " + id);
        long code = CODES[id];
        boolean[] white = new boolean[TOTAL_WIDTH * TOTAL_WIDTH];
        for (int i = 0; i < TOTAL_WIDTH; i++) {
            white[i] = white[(TOTAL_WIDTH - 1) * TOTAL_WIDTH + i] = true;   // top and bottom rows
            white[i * TOTAL_WIDTH] = white[i * TOTAL_WIDTH + TOTAL_WIDTH - 1] = true;   // left and right columns
        }
        int borderStart = (TOTAL_WIDTH - WIDTH_AT_BORDER) / 2;
        for (int i = 0; i < NBITS; i++) {
            if ((code & (1L << (NBITS - i - 1))) != 0) {
                white[(BIT_Y[i] + borderStart) * TOTAL_WIDTH + BIT_X[i] + borderStart] = true;
            }
        }
        return white;
    }
